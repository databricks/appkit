import {
  afterEach,
  beforeEach,
  describe,
  expect,
  type MockInstance,
  test,
  vi,
} from "vitest";

const tooling = vi.hoisted(() => ({
  createDbContext: vi.fn(() => ({ root: "/app", env: {} })),
  runIntrospect: vi.fn(),
}));

vi.mock("@databricks/appkit/database-tooling", () => tooling);

import { dbCommand } from "./index";

let log: MockInstance;
let error: MockInstance;
const output = (spy: MockInstance) =>
  spy.mock.calls.map((call) => call.join(" ")).join("\n");

const report = {
  branch: "projects/p/branches/dev-alice-3f9a2c",
  schemaName: "app",
  tables: ["authors", "posts"],
  schemaFile: `${process.cwd()}/config/database/schema.ts`,
  backupFile: `${process.cwd()}/config/database/schema.ts.bak`,
  skipped: [
    {
      table: "events",
      reason: "composite primary key (a, b) is not supported",
    },
    {
      table: "posts",
      column: "score",
      reason: 'type "numeric(10,2)" is not supported',
    },
  ],
  warnings: [
    "app.posts.score is NOT NULL with no default but is not in schema.ts.",
  ],
  approximated: [
    "app.authors.id: a serial key is declared as id(), an identity generated BY DEFAULT",
  ],
  migration: {
    tag: "0000_baseline",
    file: `${process.cwd()}/config/database/migrations/0000_baseline.sql`,
    statements: ["CREATE TABLE a", "CREATE TABLE b"],
  },
  recordedApplied: true,
  typesFile: `${process.cwd()}/shared/appkit-types/database.d.ts`,
};

beforeEach(() => {
  for (const option of dbCommand.commands.flatMap((c) =>
    c.options.map((o) => [c, o] as const),
  )) {
    option[0].setOptionValueWithSource(
      option[1].attributeName(),
      undefined,
      "default",
    );
  }
  tooling.runIntrospect.mockReset().mockResolvedValue(report);
  log = vi.spyOn(console, "log").mockImplementation(() => undefined);
  error = vi.spyOn(console, "error").mockImplementation(() => undefined);
});

afterEach(() => {
  vi.restoreAllMocks();
  process.exitCode = undefined;
});

describe("appkit db introspect", () => {
  test("prints the written schema, each skip, the loud warnings, and the recorded baseline", async () => {
    await dbCommand.parseAsync(["introspect"], { from: "user" });

    expect(tooling.runIntrospect).toHaveBeenCalledWith(
      { root: "/app", env: {} },
      { interactive: false },
    );
    const printed = output(log);
    expect(printed).toContain(
      "Wrote config/database/schema.ts from schema app on dev-alice-3f9a2c (2 tables); the previous file is config/database/schema.ts.bak",
    );
    expect(printed).toContain(
      "Skipped table events: composite primary key (a, b) is not supported",
    );
    expect(printed).toContain(
      'Skipped posts.score: type "numeric(10,2)" is not supported',
    );
    expect(printed).toContain("app.posts.score is NOT NULL with no default");
    expect(printed).toContain(
      "Approximated app.authors.id: a serial key is declared as id(), an identity generated BY DEFAULT",
    );
    expect(printed).toContain(
      "Generated config/database/migrations/0000_baseline.sql (2 statements)",
    );
    expect(printed).toContain(
      "Recorded 0000_baseline as applied on dev-alice-3f9a2c (its tables already exist)",
    );
    expect(printed).toContain("Generated shared/appkit-types/database.d.ts");
    expect(process.exitCode).toBeUndefined();
  });

  test("--schema-name is passed through; an unrecorded baseline says why", async () => {
    tooling.runIntrospect.mockResolvedValue({
      ...report,
      recordedApplied: false,
      notRecorded: "production is not your dev or session branch",
    });

    await dbCommand.parseAsync(["introspect", "--schema-name", "app"], {
      from: "user",
    });

    expect(tooling.runIntrospect).toHaveBeenCalledWith(expect.anything(), {
      interactive: false,
      schemaName: "app",
    });
    expect(output(log)).toContain(
      "Not recorded: production is not your dev or session branch",
    );
  });

  test("a recorded NNNN_introspect says the branch already has the changes", async () => {
    tooling.runIntrospect.mockResolvedValue({
      ...report,
      migration: { ...report.migration, tag: "0002_introspect" },
    });

    await dbCommand.parseAsync(["introspect"], { from: "user" });

    expect(output(log)).toContain(
      "Recorded 0002_introspect as applied on dev-alice-3f9a2c (the branch already has these changes)",
    );
  });

  test.each([
    [[], "No migration needed: schema.ts has no tables"],
    [
      ["authors"],
      "No migration needed: the migrations already describe this schema",
    ],
  ])("without a migration, %j tables print %j", async (tables, line) => {
    tooling.runIntrospect.mockResolvedValue({
      ...report,
      tables,
      migration: null,
      recordedApplied: false,
    });

    await dbCommand.parseAsync(["introspect"], { from: "user" });

    expect(output(log)).toContain(line);
  });

  test("a refusal is printed and exits 1", async () => {
    tooling.runIntrospect.mockRejectedValue(
      new Error(
        "Refusing to introspect production: config/database/migrations already has history",
      ),
    );

    await dbCommand.parseAsync(["introspect"], { from: "user" });

    expect(output(error)).toContain("Refusing to introspect production");
    expect(process.exitCode).toBe(1);
  });
});
