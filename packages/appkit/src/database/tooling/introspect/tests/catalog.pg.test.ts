import { randomUUID } from "node:crypto";

import { Pool } from "pg";
import { afterAll, beforeAll, describe, expect, test } from "vitest";

import { type CatalogQuery, readCatalog, readUnreadObjects } from "../catalog";

// The catalog SQL against a real server. Point it at a scratch database, e.g.
// APPKIT_TEST_PG_URL=postgres://localhost:5432/postgres
const url = process.env.APPKIT_TEST_PG_URL;

describe.skipIf(!url)("readCatalog against Postgres", () => {
  const schema = `appkit_catalog_${randomUUID().slice(0, 8)}`;
  let pool: Pool;
  const query: CatalogQuery = async <T>(
    text: string,
    values: readonly unknown[],
  ) => (await pool.query(text, [...values])).rows as T[];

  beforeAll(async () => {
    pool = new Pool({ connectionString: url, max: 1 });
    const s = `"${schema}"`;
    await pool.query(`
      create schema ${s};
      create table ${s}.__drizzle_migrations (id serial primary key, hash text not null, created_at bigint);
      create type ${s}.ticket_status as enum ('open', 'closed');
      create table ${s}.authors (
        id serial primary key,
        email varchar(255) not null unique,
        created_at timestamptz not null default now()
      );
      create table ${s}.posts (
        id integer generated by default as identity primary key,
        author_id integer not null references ${s}.authors (id) on delete cascade,
        status ${s}.ticket_status not null default 'open',
        total integer generated always as (id * 2) stored,
        score numeric(10, 2) check (score > 0)
      );
      create index posts_status_idx on ${s}.posts (status);
      create table ${s}.events (a integer, b integer, primary key (a, b));
      create table ${s}.parts (id integer primary key) partition by range (id);
      create table ${s}.parts_1 partition of ${s}.parts for values from (0) to (100);
      create table ${s}.refs (id integer primary key, part_id integer references ${s}.parts (id));

      create view ${s}.active_authors as select * from ${s}.authors;
      create materialized view ${s}.mv as select 1 as x;
      create sequence ${s}.standalone;
      create function ${s}.touch() returns trigger language plpgsql as 'begin return new; end';
      create trigger audit before update on ${s}.authors for each row execute function ${s}.touch();
      alter table ${s}.authors enable row level security;
      create policy own on ${s}.authors using (true);
      create table ${s}.base (id integer primary key);
      create table ${s}.child (extra integer) inherits (${s}.base);
      create domain ${s}.positive as integer check (value > 0);
      create type ${s}.pair as (a integer, b integer);
      create type ${s}.unused_kind as enum ('x');
    `);
  });
  afterAll(async () => {
    await pool.query(`drop schema if exists "${schema}" cascade`);
    await pool.end();
  });

  test("reads tables, keys, foreign keys, enums, generated and identity columns, and what schema.ts cannot declare", async () => {
    const tables = await readCatalog(query, schema);
    const byName = Object.fromEntries(tables.map((t) => [t.name, t]));

    expect(tables.map((t) => t.name)).toEqual([
      "authors",
      "base",
      "child",
      "events",
      "parts",
      "posts",
      "refs",
    ]);
    expect(byName.authors).toMatchObject({
      primaryKey: ["id"],
      unique: [{ name: "authors_email_key", columns: ["email"] }],
      columns: [
        {
          name: "id",
          type: "integer",
          notNull: true,
          identity: "",
          defaultExpr: `nextval('${schema}.authors_id_seq'::regclass)`,
        },
        { name: "email", type: "character varying(255)", notNull: true },
        {
          name: "created_at",
          type: "timestamp with time zone",
          defaultExpr: "now()",
        },
      ],
    });
    expect(byName.posts).toMatchObject({
      primaryKey: ["id"],
      foreignKeys: [
        {
          name: "posts_author_id_fkey",
          columns: ["author_id"],
          schema,
          table: "authors",
          refColumns: ["id"],
          onDelete: "cascade",
          onUpdate: "no action",
        },
      ],
      checks: ["posts_score_check"],
      indexes: ["posts_status_idx"],
    });
    const posts = Object.fromEntries(
      (byName.posts?.columns ?? []).map((c) => [c.name, c]),
    );
    expect(posts.id?.identity).toBe("d");
    expect(posts.total?.generated).toBe(true);
    expect(posts.status?.enum).toEqual({
      name: "ticket_status",
      schema,
      values: ["open", "closed"],
    });
    expect(byName.events?.primaryKey).toEqual(["a", "b"]);
    expect(byName.parts?.partitioned).toBe(true);
    // One foreign key, not one more per partition of its target.
    expect(byName.refs?.foreignKeys.map((fk) => fk.table)).toEqual(["parts"]);
  });

  test("names what it does not read, leaving out sequences that belong to a column", async () => {
    const unread = await readUnreadObjects(query, schema);

    expect([...unread].sort()).toEqual(
      [
        "domain positive",
        "function touch()",
        "inheritance of child from base",
        "materialized view mv",
        "policy own on authors",
        "row-level security on authors",
        "sequence standalone",
        "trigger audit on authors",
        "type pair",
        "type unused_kind",
        "view active_authors",
      ].sort(),
    );
  });
});
