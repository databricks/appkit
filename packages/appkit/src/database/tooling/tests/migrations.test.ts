import fs from "node:fs";
import os from "node:os";
import path from "node:path";

import { readMigrationFiles } from "drizzle-orm/migrator";
import { afterEach, describe, expect, test, vi } from "vitest";

import { readJournal } from "../../migrations/paths";
import {
  bigid,
  boolean,
  defineSchema,
  enumColumn,
  fk,
  id,
  integer,
  text,
  timestamp,
  varchar,
} from "../../schema-builder";
import {
  discardMigrationFiles,
  generateMigrationFiles,
  MigrationRenameAmbiguityError,
} from "../migrations";

const folders: string[] = [];

function tempFolder(): string {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "appkit-migrations-"));
  folders.push(root);
  return path.join(root, "config/database/migrations");
}

/** Every file under a folder, relative, sorted — to prove nothing was written. */
function listFiles(folder: string): string[] {
  if (!fs.existsSync(folder)) return [];
  return (fs.readdirSync(folder, { recursive: true }) as string[])
    .filter((entry) => fs.statSync(path.join(folder, entry)).isFile())
    .sort();
}

afterEach(() => {
  vi.useRealTimers();
  for (const folder of folders.splice(0)) {
    fs.rmSync(folder, { recursive: true, force: true });
  }
});

const blog = (extraPostColumns = {}) =>
  defineSchema(({ table }) => {
    const authors = table("authors", {
      id: id(),
      email: text().notNull().unique(),
      role: enumColumn("author_role", ["admin", "writer"])
        .notNull()
        .default("writer"),
      createdAt: timestamp({ withTimezone: true }).defaultNow(),
    });
    const posts = table("posts", {
      id: bigid(),
      author: fk(() => authors.id).onDelete("cascade"),
      title: varchar(120).notNull(),
      published: boolean().default(false),
      ...extraPostColumns,
    });
    return { authors, posts };
  });

describe("generateMigrationFiles", () => {
  test("writes a v7 migration from real drizzle-kit output for the builder's tables", async () => {
    const folder = tempFolder();
    const generated = await generateMigrationFiles({
      folder,
      schema: blog(),
      interactive: false,
    });

    expect(generated?.tag).toBe("0000_migration");
    expect(generated?.file).toBe(path.join(folder, "0000_migration.sql"));
    const sql = fs.readFileSync(
      path.join(folder, "0000_migration.sql"),
      "utf-8",
    );

    expect(sql).toContain(
      `CREATE TYPE "app"."author_role" AS ENUM('admin', 'writer');`,
    );
    expect(sql).toContain(`CREATE TABLE "app"."authors"`);
    expect(sql).toContain(`CREATE TABLE "app"."posts"`);
    expect(sql).toMatch(
      /"id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY/,
    );
    expect(sql).toMatch(
      /"id" bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY/,
    );
    expect(sql).toContain(
      `"role" "app"."author_role" DEFAULT 'writer' NOT NULL`,
    );
    expect(sql).toMatch(
      /FOREIGN KEY \("author"\) REFERENCES "app"\."authors"\("id"\) ON DELETE cascade/,
    );
    // The migrator creates the schema as the identity that applies it; generated SQL never does.
    expect(sql).not.toMatch(/CREATE SCHEMA/i);
    expect(sql).toContain("--> statement-breakpoint\n");

    expect(listFiles(folder)).toEqual([
      "0000_migration.sql",
      path.join("meta", "0000_snapshot.json"),
      path.join("meta", "_journal.json"),
    ]);
    const journal = readJournal(folder);
    expect(journal).toMatchObject({
      version: "7",
      dialect: "postgresql",
      entries: [
        { idx: 0, version: "7", tag: "0000_migration", breakpoints: true },
      ],
    });
    const snapshot = JSON.parse(
      fs.readFileSync(path.join(folder, "meta/0000_snapshot.json"), "utf-8"),
    );
    expect(Object.keys(snapshot.tables)).toEqual(["app.authors", "app.posts"]);
    expect(snapshot.prevId).toBe("00000000-0000-0000-0000-000000000000");
  });

  test("returns null and writes nothing when the schema matches the latest snapshot", async () => {
    const folder = tempFolder();
    await generateMigrationFiles({
      folder,
      schema: blog(),
      interactive: false,
    });
    const before = listFiles(folder).map((file) => [
      file,
      fs.readFileSync(path.join(folder, file), "utf-8"),
    ]);

    await expect(
      generateMigrationFiles({ folder, schema: blog(), interactive: false }),
    ).resolves.toBeNull();
    expect(
      listFiles(folder).map((file) => [
        file,
        fs.readFileSync(path.join(folder, file), "utf-8"),
      ]),
    ).toEqual(before);
  });

  test("an added column produces the next migration with an ALTER TABLE", async () => {
    vi.useFakeTimers({ toFake: ["Date"] });
    vi.setSystemTime(new Date("2026-01-01T00:00:00Z"));
    const folder = tempFolder();
    await generateMigrationFiles({
      folder,
      schema: blog(),
      interactive: false,
    });

    // A clock that did not move must still yield a newer journal entry.
    const next = await generateMigrationFiles({
      folder,
      schema: blog({ views: integer().notNull().default(0) }),
      interactive: false,
    });

    expect(next?.tag).toBe("0001_migration");
    expect(next?.statements).toEqual([
      `ALTER TABLE "app"."posts" ADD COLUMN "views" integer DEFAULT 0 NOT NULL;`,
    ]);
    const journal = readJournal(folder);
    expect(journal?.entries.map((entry) => entry.tag)).toEqual([
      "0000_migration",
      "0001_migration",
    ]);
    const [first, second] = journal?.entries ?? [];
    expect(second.when).toBeGreaterThan(first.when);
    const prev = JSON.parse(
      fs.readFileSync(path.join(folder, "meta/0000_snapshot.json"), "utf-8"),
    );
    const cur = JSON.parse(
      fs.readFileSync(path.join(folder, "meta/0001_snapshot.json"), "utf-8"),
    );
    expect(cur.prevId).toBe(prev.id);
  });

  test("a non-interactive column rename throws instead of prompting, and writes nothing", async () => {
    const folder = tempFolder();
    await generateMigrationFiles({
      folder,
      schema: blog({ summary: text() }),
      interactive: false,
    });
    const before = listFiles(folder);

    const error = await generateMigrationFiles({
      folder,
      schema: blog({ abstract: text() }),
      interactive: false,
    }).catch((caught: unknown) => caught);

    expect(error).toBeInstanceOf(MigrationRenameAmbiguityError);
    expect(error).toMatchObject({
      kind: "column",
      table: "app.posts",
      created: ["abstract"],
      deleted: ["summary"],
    });
    expect((error as Error).message).toMatch(/interactive terminal/);
    expect(listFiles(folder)).toEqual(before);
  });

  test("a non-interactive table rename throws too", async () => {
    const folder = tempFolder();
    const named = (name: string) =>
      defineSchema(({ table }) => ({ [name]: table(name, { id: id() }) }));
    await generateMigrationFiles({
      folder,
      schema: named("notes"),
      interactive: false,
    });

    await expect(
      generateMigrationFiles({
        folder,
        schema: named("memos"),
        interactive: false,
      }),
    ).rejects.toMatchObject({
      name: "MigrationRenameAmbiguityError",
      kind: "table",
      created: ["app.memos"],
      deleted: ["app.notes"],
    });
  });

  test("an empty schema with no history writes nothing", async () => {
    const folder = tempFolder();
    await expect(
      generateMigrationFiles({
        folder,
        schema: defineSchema(() => ({})),
        interactive: false,
      }),
    ).resolves.toBeNull();
    expect(listFiles(folder)).toEqual([]);
  });

  test("drizzle-orm's runtime migrator reads the written files", async () => {
    const folder = tempFolder();
    await generateMigrationFiles({
      folder,
      schema: blog(),
      interactive: false,
    });
    await generateMigrationFiles({
      folder,
      schema: blog({ views: integer() }),
      interactive: false,
    });

    const migrations = readMigrationFiles({ migrationsFolder: folder });
    const journal = readJournal(folder);
    expect(migrations.map((migration) => migration.folderMillis)).toEqual(
      journal?.entries.map((entry) => entry.when),
    );
    // Four statements: the enum, two tables, the FK.
    expect(migrations[0].sql).toHaveLength(4);
    expect(migrations[1].sql).toEqual([
      `ALTER TABLE "app"."posts" ADD COLUMN "views" integer;`,
    ]);
  });

  test("a non-interactive enum rename throws too, and writes nothing", async () => {
    const folder = tempFolder();
    const roles = (enumName: string) =>
      defineSchema(({ table }) => ({
        users: table("users", {
          id: id(),
          role: enumColumn(enumName, ["admin", "member"]),
        }),
      }));
    await generateMigrationFiles({
      folder,
      schema: roles("user_role"),
      interactive: false,
    });
    const before = listFiles(folder);

    const error = await generateMigrationFiles({
      folder,
      schema: roles("member_role"),
      interactive: false,
    }).catch((caught: unknown) => caught);

    expect(error).toBeInstanceOf(MigrationRenameAmbiguityError);
    expect(error).toMatchObject({
      kind: "enum",
      created: ["app.member_role"],
      deleted: ["app.user_role"],
    });
    expect(listFiles(folder)).toEqual(before);
  });

  test("refuses to diff when the latest snapshot is missing", async () => {
    const folder = tempFolder();
    await generateMigrationFiles({
      folder,
      schema: blog(),
      interactive: false,
    });
    fs.rmSync(path.join(folder, "meta/0000_snapshot.json"));
    await expect(
      generateMigrationFiles({
        folder,
        schema: blog({ views: integer() }),
        interactive: false,
      }),
    ).rejects.toThrow(/Restore it from version control/);
  });

  test("a corrupt snapshot names the file and how to recover", async () => {
    const folder = tempFolder();
    await generateMigrationFiles({
      folder,
      schema: blog(),
      interactive: false,
    });
    const snapshot = path.join(folder, "meta/0000_snapshot.json");
    fs.writeFileSync(snapshot, "{ not json");

    await expect(
      generateMigrationFiles({
        folder,
        schema: blog({ views: integer() }),
        interactive: false,
      }),
    ).rejects.toThrow(
      new RegExp(
        `^Cannot read ${snapshot.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}: .+\\. Restore it from version control\\.$`,
      ),
    );
  });
});

describe("discardMigrationFiles", () => {
  test("a first migration goes with the folders it created", async () => {
    const folder = tempFolder();
    const migration = await generateMigrationFiles({
      folder,
      schema: blog(),
      interactive: false,
    });

    discardMigrationFiles(folder, migration as never, null);

    expect(fs.existsSync(folder)).toBe(false);
  });

  test("a later migration goes, and the previous journal comes back byte for byte", async () => {
    const folder = tempFolder();
    await generateMigrationFiles({
      folder,
      schema: blog(),
      interactive: false,
    });
    const journalFile = path.join(folder, "meta/_journal.json");
    const journalBefore = `${fs.readFileSync(journalFile, "utf-8")}\n`;
    fs.writeFileSync(journalFile, journalBefore);
    const filesBefore = listFiles(folder);
    const migration = await generateMigrationFiles({
      folder,
      schema: blog({ summary: text() }),
      interactive: false,
    });
    expect(listFiles(folder)).not.toEqual(filesBefore);

    discardMigrationFiles(folder, migration as never, journalBefore);

    expect(listFiles(folder)).toEqual(filesBefore);
    expect(fs.readFileSync(journalFile, "utf-8")).toBe(journalBefore);
  });
});
